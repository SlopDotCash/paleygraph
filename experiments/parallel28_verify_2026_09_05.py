CHECKS=Counter()
def check(ok,key):
    assert ok,key
    CHECKS[key]+=1
def H(path): return sha256((ROOT/path).read_bytes()).hexdigest()

def energy(f,p):
    conv=[0]*p
    support=[(i,x) for i,x in enumerate(f) if x]
    for a,x in support:
        for b,y in support: conv[(a+b)%p]+=x*y
    return sum(x*x for x in conv)

def weighted_cases():
    rng=random.Random(280905)
    reports=[]
    # Square subgroup orders make every tested upper bound rational.
    for p,n in [(5,4),(13,4),(17,4),(29,4),(17,16),(97,16),(193,64)]:
        group=M.subgroup(p,n)
        remaining=set(range(1,p));cosets=[]
        while remaining:
            a=min(remaining);c={a*h%p for h in group}
            remaining-=c;cosets.append(sorted(c))
        # Check the unweighted premise for every union of nonzero cosets.
        for mask in range(1,1<<len(cosets)):
            f=[0]*p
            for i,c in enumerate(cosets):
                if mask>>i&1:
                    for x in c:f[x]=1
            a=sum(f)
            check(energy(f,p)<=F(a**4,p)+F(a**3,isqrt(n)),
                  'all_invariant_sets_Cstar_one_in_selected_fields')
        for trial in range(16):
            f=[0]*p
            weights=[rng.randrange(9) if trial%2 else 2**rng.randrange(13) for _ in cosets]
            for c,w in zip(cosets,weights):
                for x in c:f[x]=w
            a=sum(f);b=sum(x*x for x in f);e=energy(f,p)
            check(e<=8*F(a**4,p)+10368*F(a*a*b,isqrt(n)),
                  'weighted_lifting_exact_finite_check')
        # Exact cyclic convolution counts, with the origin retained.
        r=[0]*p;r[0]=1;energies={};origins={}
        for s in range(1,13):
            nxt=[0]*p
            for x,v in enumerate(r):
                for h in group:nxt[(x+h)%p]+=v
            r=nxt;energies[s]=sum(v*v for v in r);origins[s]=r[0]
            check(sum(r)==n**s,'convolution_total_mass')
            check(r[0]<=n**(s-1),'origin_pointwise_bound')
            check(r[0]**4<=n**(2*s-2)*energies[s],'origin_energy_absorption')
            if s%2==0:
                t=s//2
                check(energies[s]<=82952*(F(n**(4*t),p)+F(n**(2*t)*energies[t],isqrt(n))),
                      'recurrence_exact_finite_check')
        reports.append({'p':p,'n':n,'invariant_cosets':len(cosets),
                        'energies':energies,'origin_counts':origins})
    return reports

def exponent_ledger():
    check(8*6**4==10368,'first_weighted_constant')
    check(8*10368+8==82952,'recurrence_constant')
    check(F(18)+4+F(11,2)+4+4==F(71,2),'second_term_total_power')
    check(F(71,2)/36==F(71,72),'amplitude_power')
    check(F(2,36)==F(1,18),'refined_log_power')
    check(F(6,36)==F(1,6),'published_recurrence_log_power')
    check(F(2849,2880)-F(71,72)==F(1,320),'baseline_power_improvement')
    # The concave energy-deficit envelope generated by the stated seeds,
    # recurrence, interpolation and the principal floor at p ~ n^4.
    knots={1:F(1),2:F(31,20),3:F(2),6:F(5,2),12:F(3),24:F(7,2),48:F(4)}
    candidates=[{'k':k,'l':l,'saving':str((dk+dl-4)/(2*k*l))}
                for k,dk in knots.items() for l,dl in knots.items()]
    best=max(F(r['saving']) for r in candidates)
    check(best==F(1,72),'mixed_moment_ledger_maximum')
    return {'knots':{k:str(v) for k,v in knots.items()},'candidates':candidates,
            'best_saving':str(best),'maximizers':[r for r in candidates if F(r['saving'])==best],
            'scope':'Finite endpoint check for the explicitly proved piecewise envelope; not an optimality theorem for all analytic methods.'}

def direct_cases():
    data=json.loads((ROOT/'results/parallel28_complete_remainder_2026_09_05.json').read_text())
    chosen={}
    for row in data['cases']:
        signature=tuple(row[k] for k in ['n','E2','J6','repeated_R6','distinct_balanced_R6','distinct_unbalanced_R6'])
        chosen.setdefault(signature,row)
    selected={(r['p'],r['n']):r for r in chosen.values()}
    for row in data['cases']:
        summary=data['per_order'][str(row['n'])]
        if row['n']>=32 and row['p'] in summary['maximizers']:
            selected[(row['p'],row['n'])]=row
    verified=[]
    with tempfile.TemporaryDirectory(prefix='paley-pass28-') as tmp:
        exe=Path(tmp)/'direct'
        subprocess.run(['/usr/bin/clang++','-O3','-std=c++17','-Wall','-Wextra',
            str(ROOT/'experiments/parallel27_direct_six.cpp'),'-o',str(exe)],check=True,capture_output=True)
        for key,row in sorted(selected.items()):
            got=json.loads(subprocess.run([str(exe)],input=f'{key[0]} {key[1]}\n',
                text=True,capture_output=True,check=True).stdout)
            for k in ['E3','T6','J6','repeated_R6','distinct_balanced_R6','distinct_unbalanced_R6']:
                check(got[k]==row[k],'independent_direct_six_category')
            verified.append(got)
    return verified

