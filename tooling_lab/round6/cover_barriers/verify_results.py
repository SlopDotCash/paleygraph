#!/usr/bin/env python3
"""Source-bound full ledger replay and exact cap-attainment verification."""
from hashlib import sha256
import json
from math import comb
from pathlib import Path
import subprocess
import sys
sys.dont_write_bytecode = True
from cover_barriers import *
from compressed_support import domain


def main():
    data = json.loads((HERE / 'results.json').read_text())
    for name, expected in data['source_sha256'].items():
        assert sha256((HERE / name).read_bytes()).hexdigest() == expected, name
    for name, expected in data['artifact_sha256'].items():
        assert sha256((HERE / name).read_bytes()).hexdigest() == expected, name
    for name, expected in data['dependency_sha256'].items():
        assert sha256((LAB / name).read_bytes()).hexdigest() == expected, name
    originals = json.loads((LAB / 'proximity/stack_results.json').read_text())['records']
    original_map = {(x['configuration'], x['sample']): x for x in originals}
    assert {(x['configuration'], x['sample']) for x in data['hard_stacks']} == set(original_map)
    groups = {}
    for row in data['hard_stacks']:
        groups.setdefault(row['configuration'], []).append(row)
    counts = {'hard_pencils': 0, 'bases_per_sample_replayed': 0, 'scalar_and_joint_maxima': 0,
              'actual_minimum_cap_attainments': 0, 'joint_family_obstructions': 0,
              'large_partition_upper_bound_certificates': 0}
    for name, rows in groups.items():
        expected_input = [rows[0]['field']['p'], rows[0]['n'], rows[0]['k'], len(rows)] + rows[0]['domain']
        for row in rows:
            expected_input.extend(row['u0'] + row['u1'])
        assert list(map(int, (HERE / f'{name}.input.txt').read_text().split())) == expected_input
        new = HERE / f'{name}.readback.json'
        subprocess.run([str(HERE / 'base_census'), 'verify', str(HERE / f'{name}.input.txt'),
                        str(HERE / f'{name}.supports.bin'), str(new)], check=True)
        replay = json.loads(new.read_text())
        assert len(replay['samples']) == len(rows)
        assert replay['basis_count'] == comb(rows[0]['n'], rows[0]['k'])
        for row, summary in zip(rows, replay['samples']):
            original = original_map[(name, row['sample'])]
            for key in ['n', 'k', 's', 'u0', 'u1']:
                assert row[key] == original[key]
            assert row['field']['p'] == original['p']
            assert row['exact_maxima_u0_u1_joint'] == summary['maxima_u0_u1_joint']
            F = PrimeField(row['field']['p'])
            dom, n, k, s = row['domain'], row['n'], row['k'], row['s']
            assert dom == domain(n, F.p)
            for j, witness in enumerate(row['maximum_witnesses']):
                words = [row['u0'], row['u1']] if j == 2 else [row['u0' if j == 0 else 'u1']]
                assert witness['base'] == summary['witness_bases'][j]
                assert sum(1 << i for i in witness['support']) == summary['witness_support_masks'][j]
                assert len(witness['support']) == row['exact_maxima_u0_u1_joint'][j]
                assert row['actual_cap_minimum_attainment_u0_u1_joint'][j] == attain_from_maximum(F, dom, k, words, witness)
                assert row['barriers_u0_u1_joint'][j] == cap_barrier(n, k, s, len(witness['support']), 'exact_maximum')
                counts['scalar_and_joint_maxima'] += 1
                counts['actual_minimum_cap_attainments'] += 1
            assert row['barriers_u0_u1_joint'][2]['status'] == 'entire_root_count_cap_family_blocked'
            counts['joint_family_obstructions'] += 1
            counts['hard_pencils'] += 1
            counts['bases_per_sample_replayed'] += comb(n, k)
    for row in data['large_structured']:
        F = PrimeField(row['field']['p'])
        proof = row['bound_certificate']
        assert proof == polynomial_partition_bound(F, row['domain'], row['k'], row['u0'], row['u1'], proof['tracks'])
        assert row['barrier'] == cap_barrier(row['n'], row['k'], row['s'], proof['M'], proof['proof_kind'])
        quarter = row['same_input_at_k256']['bound_certificate']
        assert quarter == polynomial_partition_bound(F, row['domain'], 256, row['u0'], row['u1'], quarter['tracks'])
        assert row['same_input_at_k256']['barrier_at_s566'] == cap_barrier(1024, 256, 566, quarter['M'], quarter['proof_kind'])
        counts['large_partition_upper_bound_certificates'] += 2
    for row in data['rate_quarter']:
        n, k, s, M = (row[x] for x in ['n', 'k', 's', 'minimum_M_not_blocked_by_abstract_cap'])
        assert minimum_cap(n, k, M)['minimum'] < s
        assert M == 1 or minimum_cap(n, k, M - 1)['minimum'] >= s
    report = {'status': 'passed', 'counts': counts,
              'scope': 'complete Newton replay of support masks generated by barycentric interpolation; Python checks all maximum witnesses and attaining partitions',
              'source_sha256': {**data['source_sha256'], 'verify_results.py': sha256((HERE / 'verify_results.py').read_bytes()).hexdigest()},
              'dependency_sha256': data['dependency_sha256'],
              'results_sha256': sha256((HERE / 'results.json').read_bytes()).hexdigest()}
    (HERE / 'verification.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
